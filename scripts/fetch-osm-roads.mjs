// Downloads the real OSM drivable road network for the Mahadevapura pilot
// bbox from Overpass and writes a compact snapshot to src/data/osm-roads.json.
// Run from a plain Node process (server runtimes may block outbound fetch):
//   node scripts/fetch-osm-roads.mjs
import { writeFileSync } from "node:fs";

const BBOX = { south: 12.91, west: 77.66, north: 13.0, east: 77.775 };
const QUERY = `[out:json][timeout:60];way["highway"~"^(trunk|primary|secondary|tertiary|unclassified|residential|living_street)$"](${BBOX.south},${BBOX.west},${BBOX.north},${BBOX.east});out tags geom;`;

const response = await fetch("https://overpass-api.de/api/interpreter", {
  method: "POST",
  // Overpass's Apache rejects undici's default UA with 406 Not Acceptable.
  headers: { "content-type": "application/x-www-form-urlencoded", "user-agent": "bengaluru-smart-waste-demo/1.0 (OSM snapshot script)", accept: "application/json" },
  body: "data=" + encodeURIComponent(QUERY),
});
if (!response.ok) throw new Error(`Overpass returned ${response.status}`);
const body = await response.json();

const DRIVABLE = /^(trunk|primary|secondary|tertiary|unclassified|residential|living_street)$/;
const round5 = (value) => Math.round(value * 1e5) / 1e5;
const ways = [];
for (const element of body.elements ?? []) {
  if (element.type !== "way" || !element.geometry?.length) continue;
  const highway = element.tags?.highway;
  if (!highway || !DRIVABLE.test(highway)) continue;
  const oneway = element.tags?.oneway === "yes" || element.tags?.oneway === "1" ? 1 : element.tags?.oneway === "-1" ? -1 : 0;
  const coords = [];
  let lastLat = null;
  let lastLng = null;
  for (const node of element.geometry) {
    const lat = round5(node.lat);
    const lng = round5(node.lon);
    if (lat === lastLat && lng === lastLng) continue;
    coords.push(lat, lng);
    lastLat = lat;
    lastLng = lng;
  }
  if (coords.length >= 4) ways.push([highway, oneway, coords]);
}

const snapshot = {
  version: 1,
  fetchedAt: new Date().toISOString(),
  source: "OpenStreetMap via Overpass API (ODbL)",
  bbox: BBOX,
  ways,
};
// Written as a .ts module (not .json): vinext's dev SSR runner loads TS modules
// reliably, while large JSON module imports in dynamic chains proved flaky.
const moduleSource = `// AUTO-GENERATED by scripts/fetch-osm-roads.mjs — do not edit by hand.
// Real OpenStreetMap drivable-road snapshot for the Mahadevapura pilot bbox.
export type OsmRoadSnapshotWay = [highway: string, oneway: 0 | 1 | -1, coords: number[]];
export type OsmRoadSnapshot = { version: number; fetchedAt: string; source: string; bbox: { south: number; west: number; north: number; east: number }; ways: OsmRoadSnapshotWay[] };
export const osmRoads: OsmRoadSnapshot = ${JSON.stringify(snapshot)};
`;
writeFileSync(new URL("../src/data/osm-roads.ts", import.meta.url), moduleSource);
const nodeCount = ways.reduce((sum, way) => sum + way[2].length / 2, 0);
console.log(`wrote src/data/osm-roads.ts: ${ways.length} ways, ~${nodeCount} nodes, ${(moduleSource.length / 1e6).toFixed(2)} MB`);
